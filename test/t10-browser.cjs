const assert=require('node:assert/strict');
const {chromium:pw}=require('playwright-core');
const chromium=require('@sparticuz/chromium').default;
(async()=>{
 const browser=await pw.launch({executablePath:await chromium.executablePath(),headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
 const context=await browser.newContext({viewport:{width:390,height:844}});
 const page=await context.newPage(),errors=[];
 page.on('pageerror',e=>errors.push(String(e)));
 await page.goto('http://127.0.0.1:4178/t10-review/',{waitUntil:'networkidle'});
 await page.click('#loadDemo');
 await page.waitForFunction(()=>document.querySelector('h2')?.textContent.includes('عينة T10'));
 const body=await page.locator('#app').innerText();
 assert.ok(body.includes('3')&&body.includes('منصة مؤكدة'),'three confirmed social platforms shown');
 assert.ok(body.includes('9')&&body.includes('منشور مؤرخ'),'dated sample total shown');
 assert.ok(body.includes('مفيش منشورات مؤرخة ومعتمدة اتقرت'),'no-sample platform explicit');
 assert.ok(body.includes('أقدم من 90 يوم'),'old activity disclosed');
 const cards=page.locator('.platform');assert.equal(await cards.count(),3,'three platform cards');
 const fb=cards.filter({hasText:'فيسبوك — عينة'});
 assert.ok((await fb.innerText()).includes('8')&&(await fb.innerText()).includes('37.5٪'),'facebook mix calculated from eight posts');
 const ig=cards.filter({hasText:'إنستجرام — بلا منشورات مقروءة'});
 assert.equal(await ig.locator('.bar-row').count(),0,'no bars without dated sample');
 const select=fb.locator('.postType').first();await select.selectOption('brand');
 await page.waitForFunction(()=>document.body.innerText.includes('تصحيح الفريق'));
 await page.reload({waitUntil:'networkidle'});
 const stored=await page.evaluate(()=>JSON.parse(localStorage.getItem('tt_rebuild_t05_current')));
 const c=stored.clients.find(x=>x.id==='client_t10_acceptance_sample'),post=c.contentSamples.find(x=>x.sourceId==='t10_fb').posts[0];
 assert.equal(post.teamType,'brand','team correction preserved after refresh');
 const dims=await page.evaluate(()=>({sw:document.documentElement.scrollWidth,cw:document.documentElement.clientWidth}));
 assert.equal(dims.sw,dims.cw,'no horizontal scroll at 390px');
 assert.deepEqual(errors,[],'no page errors');
 console.log(JSON.stringify({passed:true,platformCards:3,datedPosts:9,noSampleNoPercent:true,oldActivityShown:true,correctionPersists:true,mobile:dims}));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});